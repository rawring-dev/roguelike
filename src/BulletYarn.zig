const frames = 7;
const sprite = [112]u8{ 0xaa, 0xaa, 0xaa, 0xaa, 0x99, 0xaa, 0xa4, 0x46, 0xaa, 0x9a, 0x80, 0xaa, 0xaa, 0xaa, 0xaa, 0xa0, 0xaa, 0xaa, 0x45, 0x2a, 0xa4, 0x5a, 0xaa, 0x41, 0x85, 0xaa, 0xaa, 0x02, 0xa5, 0x54, 0x85, 0x50, 0x11, 0x5a, 0xa1, 0x16, 0x18, 0x40, 0xa6, 0xaa, 0xaa, 0x56, 0x86, 0xa9, 0x56, 0xa4, 0x44, 0x9a, 0xa9, 0x12, 0x11, 0x16, 0xa6, 0x46, 0xa9, 0x6a, 0x54, 0x6a, 0x94, 0x64, 0x91, 0x9a, 0x92, 0x9a, 0x16, 0x95, 0xa6, 0x11, 0x96, 0xaa, 0x91, 0x2a, 0x01, 0x2a, 0xa8, 0x5a, 0x15, 0x5a, 0x05, 0x52, 0xa5, 0x44, 0x84, 0x6a, 0x44, 0x6a, 0x41, 0xaa, 0xa9, 0x52, 0x96, 0xaa, 0xaa, 0xaa, 0xa8, 0x51, 0x94, 0x5a, 0x91, 0xaa, 0xa6, 0xaa, 0xa8, 0x02, 0x82, 0xaa, 0xaa, 0xaa, 0xaa, 0x66, 0x94, 0x1a };

bullet: Bullet,
anim_timer: u8 = 0,

pub fn init(bullet: Bullet) Self {
    return .{ .bullet = bullet };
}

pub fn update(self: *Self) void {
    self.bullet.update();
    self.anim_timer += 1;
}
pub fn draw(self: *const Self, camera_x: i32, camera_y: i32) void {
    w4.DRAW_COLORS.* = 0x42;
    const frame_speed = 12; // how many frames per 1 animation frame
    w4.blitSub(
        &sprite,
        @as(i32, @trunc(self.bullet.x)) - camera_x,
        @as(i32, @trunc(self.bullet.y)) - camera_y,
        w,
        h,
        ((self.anim_timer / frame_speed) % frames) * w,
        0,
        w * frames,
        w4.BLIT_2BPP,
    );
}

pub fn collisionRect(self: *const Self) collision.Rect {
    return collision.Rect{
        .x = self.bullet.x,
        .y = self.bullet.y,
        .w = 8,
        .h = 8,
    };
}
